// Bundles server/index.mjs and its dependencies (MCP SDK, zod) into one committed file, server/bundle.mjs,
// so the plugin runs with plain `node` and no npm install. Re-run after changing server/ or lib/ (npm run bundle).
//   node tools/bundle.mjs           write server/bundle.mjs
//   node tools/bundle.mjs --check   fail if the committed bundle is out of date (used by npm test)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outfile = path.join(root, "server", "bundle.mjs");
const check = process.argv.includes("--check");
const result = await build({
  entryPoints: [path.join(root, "server", "index.mjs")],
  outfile,
  write: !check,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node18",
  legalComments: "eof", // keep the dependencies' licence notices
  // some bundled dependencies are CommonJS and call require() for Node built-ins
  banner: { js: "// Generated by tools/bundle.mjs from server/index.mjs. Do not edit; run npm run bundle.\nimport { createRequire as __rbCreateRequire } from 'node:module';\nconst require = __rbCreateRequire(import.meta.url);" },
  logLevel: check ? "warning" : "info",
});
if (check) {
  const fresh = result.outputFiles[0].text;
  const committed = fs.existsSync(outfile) ? fs.readFileSync(outfile, "utf8") : "";
  if (fresh !== committed) { console.error("server/bundle.mjs is out of date: run npm run bundle"); process.exit(1); }
  console.log("bundle up to date");
}
